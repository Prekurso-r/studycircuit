function choice(topic, level, slug, prompt, correct, distractors, explanation, figure) {
  const answer = (topic + slug.length) % 4;
  const options = [...distractors];
  options.splice(answer, 0, correct);
  return {
    id: 'math-2-' + topic + '-' + slug, bank: 'mathematics-2.' + topic,
    level, prompt, options, answer, explanation, ...(figure && { figure }),
  };
}

function numeric(topic, slug, prompt, parts, explanation, figure) {
  return {
    id: 'math-2-' + topic + '-' + slug, bank: 'mathematics-2.' + topic,
    level: 'challenge', prompt, parts: parts.map(([label, answer, tolerance]) => ({
      label, answer, tolerance, unit: '',
    })), explanation, ...(figure && { figure }),
  };
}

function table(caption, headers, rows) {
  return { caption, headers, rows };
}

function plot(caption, alt, xTicks, yTicks, series, labels = []) {
  const width = 440;
  const height = 230;
  const left = 42;
  const right = 418;
  const top = 18;
  const bottom = 198;
  const xMin = xTicks[0];
  const xMax = xTicks.at(-1);
  const yMin = yTicks[0];
  const yMax = yTicks.at(-1);
  const xPixel = x => left + (x - xMin) / (xMax - xMin) * (right - left);
  const yPixel = y => bottom - (y - yMin) / (yMax - yMin) * (bottom - top);
  const coords = ([x, y]) => xPixel(x).toFixed(1) + ',' + yPixel(y).toFixed(1);
  const xGrid = xTicks.map(x => '<path d="M ' + xPixel(x) + ' ' + top + ' V ' + bottom + '"/>').join('');
  const yGrid = yTicks.map(y => '<path d="M ' + left + ' ' + yPixel(y) + ' H ' + right + '"/>').join('');
  const xLabels = xTicks.map(x => '<text x="' + xPixel(x) + '" y="215" text-anchor="middle">' + x + '</text>').join('');
  const yLabels = yTicks.map(y => '<text x="32" y="' + (yPixel(y) + 4) + '" text-anchor="end">' + y + '</text>').join('');
  const lines = series.map(({ points, color, dashed }) => '<polyline points="' + points.map(coords).join(' ') +
    '" fill="none" stroke="' + color + '" stroke-width="2.8" stroke-linejoin="round"' +
    (dashed ? ' stroke-dasharray="7 5"' : '') + '/>').join('');
  const annotations = labels.map(([x, y, label]) => '<text x="' + xPixel(x) + '" y="' +
    yPixel(y) + '" dominant-baseline="mathematical">' + label + '</text>').join('');
  const svg = '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ' + width + ' ' + height +
    '" font-family="system-ui,sans-serif" font-size="13" fill="#28233b" aria-hidden="true">' +
    '<g stroke="#ded8e8">' + xGrid + yGrid + '</g><path d="M ' + left + ' ' + top + ' V ' +
    bottom + ' H ' + right + '" stroke="#28233b" stroke-width="1.6" fill="none"/>' +
    xLabels + yLabels + '<text x="429" y="201">x</text><text x="40" y="13">y</text>' +
    lines + annotations + '</svg>';
  return { caption, alt, svg };
}

